create index daily_runs_group_idx on public.daily_runs (daily_group_id, created_at desc);
create index daily_run_members_member_idx on public.daily_run_members (daily_member_id);
create index templates_variant_idx on public.templates (variant_id, project_id);
create index qa_generations_user_idx on public.qa_generations (user_id, created_at desc);
create index qa_generations_project_idx on public.qa_generations (project_id);
create index qa_generations_variant_idx on public.qa_generations (variant_id);
create index qa_generation_items_generation_idx on public.qa_generation_items (generation_id);
create index qa_generation_items_pbi_idx on public.qa_generation_items (pbi_number);
create index qa_generation_tasks_item_idx on public.qa_generation_tasks (generation_item_id);
create index ai_usage_log_user_idx on public.ai_usage_log (user_id, created_at desc);
