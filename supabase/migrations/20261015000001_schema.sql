-- QA BCR Suite v3 — Fase 1.1: esquema
-- Requiere Postgres 15+ (usa UNIQUE NULLS NOT DISTINCT). Supabase ya lo cumple.

-- ─────────────────────────────────────────────────────────────
-- Utilidad: mantener updated_at
-- ─────────────────────────────────────────────────────────────
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

-- ─────────────────────────────────────────────────────────────
-- Usuarios
-- ─────────────────────────────────────────────────────────────
create table public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    full_name text not null,
    email text,
    role text not null default 'QA'
        check (role in ('ADMIN', 'QA_LEAD', 'QA')),
    active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create trigger profiles_updated_at
before update on public.profiles
for each row execute function public.set_updated_at();

-- Cada usuario creado en Supabase Auth recibe un perfil QA activo.
-- El nombre se toma de user_metadata.full_name; si no viene, del correo.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    insert into public.profiles (id, full_name, email)
    values (
        new.id,
        coalesce(nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''), new.email),
        new.email
    );
    return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

-- ─────────────────────────────────────────────────────────────
-- Daily
-- ─────────────────────────────────────────────────────────────
create table public.daily_groups (
    id bigint generated by default as identity primary key,
    code text not null unique,
    name text not null,
    active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create trigger daily_groups_updated_at
before update on public.daily_groups
for each row execute function public.set_updated_at();

create table public.daily_members (
    id bigint generated by default as identity primary key,
    daily_group_id bigint not null references public.daily_groups(id) on delete cascade,
    name text not null check (trim(name) <> ''),
    active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (daily_group_id, name)
);

create trigger daily_members_updated_at
before update on public.daily_members
for each row execute function public.set_updated_at();

create table public.daily_rules (
    id bigint generated by default as identity primary key,
    daily_group_id bigint not null unique references public.daily_groups(id) on delete cascade,
    first_range integer not null default 1 check (first_range >= 0),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create trigger daily_rules_updated_at
before update on public.daily_rules
for each row execute function public.set_updated_at();

-- Una persona tiene como máximo una regla: la app actual quita
-- FIRST_GROUP al marcar LAST_FIXED y viceversa. Por eso la unicidad
-- es solo por persona, y el cambio de regla es un upsert:
--   insert ... on conflict (daily_member_id) do update set rule_type = excluded.rule_type
create table public.daily_rule_members (
    id bigint generated by default as identity primary key,
    daily_member_id bigint not null unique references public.daily_members(id) on delete cascade,
    rule_type text not null check (rule_type in ('FIRST_GROUP', 'LAST_FIXED')),
    created_at timestamptz not null default now()
);

create table public.daily_runs (
    id bigint generated by default as identity primary key,
    daily_group_id bigint not null references public.daily_groups(id),
    created_by uuid default auth.uid() references auth.users(id) on delete set null,
    created_at timestamptz not null default now()
);

-- member_name conserva el histórico aunque la persona cambie de nombre o se borre.
create table public.daily_run_members (
    id bigint generated by default as identity primary key,
    daily_run_id bigint not null references public.daily_runs(id) on delete cascade,
    daily_member_id bigint references public.daily_members(id) on delete set null,
    member_name text not null,
    position integer not null check (position >= 1),
    completed boolean not null default false,
    created_at timestamptz not null default now(),
    unique (daily_run_id, position)
);

-- ─────────────────────────────────────────────────────────────
-- Proyectos y plantillas
-- ─────────────────────────────────────────────────────────────
create table public.projects (
    id bigint generated by default as identity primary key,
    code text not null unique check (trim(code) <> ''),
    name text not null,
    color text check (color ~ '^#[0-9a-fA-F]{6}$'),
    active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create trigger projects_updated_at
before update on public.projects
for each row execute function public.set_updated_at();

create table public.project_variants (
    id bigint generated by default as identity primary key,
    project_id bigint not null references public.projects(id) on delete cascade,
    name text not null check (trim(name) <> ''),
    active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (project_id, name),
    -- destino de la FK compuesta de templates
    unique (id, project_id)
);

create trigger project_variants_updated_at
before update on public.project_variants
for each row execute function public.set_updated_at();

-- variant_id null = plantilla del proyecto sin variante (la clave '' del JSON).
-- NULLS NOT DISTINCT impide dos plantillas sin variante en el mismo proyecto.
-- La FK compuesta impide usar una variante de otro proyecto.
create table public.templates (
    id bigint generated by default as identity primary key,
    project_id bigint not null references public.projects(id) on delete cascade,
    variant_id bigint,
    active boolean not null default true,
    created_by uuid default auth.uid() references auth.users(id) on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint templates_project_variant_key unique nulls not distinct (project_id, variant_id),
    constraint templates_variant_fkey foreign key (variant_id, project_id)
        references public.project_variants(id, project_id) on delete cascade
);

create trigger templates_updated_at
before update on public.templates
for each row execute function public.set_updated_at();

create table public.template_tasks (
    id bigint generated by default as identity primary key,
    template_id bigint not null references public.templates(id) on delete cascade,
    position integer not null check (position >= 1),
    task text not null check (trim(task) <> ''),
    created_at timestamptz not null default now(),
    unique (template_id, position)
);

-- ─────────────────────────────────────────────────────────────
-- Historial del QA Generator
-- project_name y variant_name guardan lo que se usó en ese momento,
-- aunque luego se renombre o se desactive el proyecto.
-- ─────────────────────────────────────────────────────────────
create table public.qa_generations (
    id bigint generated by default as identity primary key,
    user_id uuid not null default auth.uid() references auth.users(id),
    project_id bigint references public.projects(id) on delete set null,
    variant_id bigint references public.project_variants(id) on delete set null,
    project_name text not null,
    variant_name text,
    created_at timestamptz not null default now()
);

create table public.qa_generation_items (
    id bigint generated by default as identity primary key,
    generation_id bigint not null references public.qa_generations(id) on delete cascade,
    pbi_number text,
    pbi_text text not null,
    created_at timestamptz not null default now()
);

create table public.qa_generation_tasks (
    id bigint generated by default as identity primary key,
    generation_item_id bigint not null references public.qa_generation_items(id) on delete cascade,
    position integer not null check (position >= 1),
    task text not null,
    created_at timestamptz not null default now()
);

-- ─────────────────────────────────────────────────────────────
-- Uso de IA (lo escribe la Edge Function de la Fase 4)
-- ─────────────────────────────────────────────────────────────
create table public.ai_usage_log (
    id bigint generated by default as identity primary key,
    user_id uuid references auth.users(id) on delete set null,
    action text not null check (action in ('extract_pbis', 'generate_tasks')),
    success boolean not null,
    created_at timestamptz not null default now()
);

-- ─────────────────────────────────────────────────────────────
-- Índices para FKs y consultas de historial
