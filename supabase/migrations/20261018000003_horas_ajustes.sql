-- QA BCR Suite v3 — Ajustes al consolidado de horas
-- QA_LEAD y ADMIN pueden corregir un número del consolidado semanal sin tocar
-- las líneas del QA: se guarda la diferencia (delta) con un motivo.
--   · Se ajusta por semana. Una semana que cruza de mes son dos tramos, y cada
--     ajuste es de un tramo: "fecha" es el primer día del tramo (lunes, o el 1
--     del mes). El mes suma los ajustes de sus tramos, así semana y mes cuadran.
--   · Se guarda la diferencia y no el número final: si el QA después agrega una
--     línea, el ajuste se mantiene sobre lo nuevo.
--   · horas_resumen() devuelve los números ya ajustados (todos ven el número
--     final). El detalle (quién, motivo, diferencia) solo lo leen QA_LEAD y ADMIN.
-- Requiere 20261018000002_horas_informe.sql.

create table public.horas_ajustes (
    id bigint generated by default as identity primary key,
    user_id uuid not null references public.profiles(id) on delete cascade,
    fecha date not null check (
        extract(isodow from fecha) between 1 and 5
        and (extract(isodow from fecha) = 1 or extract(day from fecha) = 1)
    ),
    columna text not null
        check (columna in ('feriado', 'facturable', 'no_facturable', 'licencia', 'vacaciones')),
    delta numeric(6, 2) not null check (delta <> 0 and delta between -500 and 500),
    motivo text not null check (char_length(btrim(motivo)) between 1 and 200),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    updated_by uuid references public.profiles(id) on delete set null,
    constraint horas_ajustes_unico unique (user_id, fecha, columna)
);

create index horas_ajustes_fecha on public.horas_ajustes (fecha);

create or replace function public.horas_ajustes_touch()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.updated_at = now();
    new.updated_by = auth.uid();
    if tg_op = 'INSERT' then
        new.created_at = now();
    end if;
    return new;
end;
$$;

create trigger horas_ajustes_touch
before insert or update on public.horas_ajustes
for each row execute function public.horas_ajustes_touch();

alter table public.horas_ajustes enable row level security;

create policy horas_ajustes_select
on public.horas_ajustes for select to authenticated
using ((select private.is_lead()));

create policy horas_ajustes_insert
on public.horas_ajustes for insert to authenticated
with check ((select private.is_lead()));

create policy horas_ajustes_update
on public.horas_ajustes for update to authenticated
using ((select private.is_lead()))
with check ((select private.is_lead()));

create policy horas_ajustes_delete
on public.horas_ajustes for delete to authenticated
using ((select private.is_lead()));

grant select, delete on public.horas_ajustes to authenticated;
grant insert (user_id, fecha, columna, delta, motivo) on public.horas_ajustes to authenticated;
grant update (delta, motivo) on public.horas_ajustes to authenticated;
grant usage, select on sequence public.horas_ajustes_id_seq to authenticated;
revoke all on public.horas_ajustes from anon;
grant all on public.horas_ajustes to service_role;

-- Mismo consolidado, con los ajustes sumados.
create or replace function public.horas_resumen(desde date, hasta date)
returns table (
    user_id uuid,
    full_name text,
    feriado numeric,
    facturable numeric,
    no_facturable numeric,
    licencia numeric,
    vacaciones numeric,
    total numeric
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
    if not private.is_active_user() then
        raise exception 'Usuario sin acceso' using errcode = '42501';
    end if;
    if desde is null or hasta is null or hasta < desde or hasta - desde > 62 then
        raise exception 'Período inválido' using errcode = '22023';
    end if;
    return query
        with h as (
            select x.user_id,
                   coalesce(sum(x.horas) filter (where x.tipo = 'FERIADO'), 0) as feriado,
                   coalesce(sum(x.facturable) filter (where x.tipo = 'TRABAJO'), 0) as facturable,
                   coalesce(sum(x.horas - x.facturable) filter (where x.tipo = 'TRABAJO'), 0) as no_facturable,
                   coalesce(sum(x.horas) filter (where x.tipo = 'LICENCIA'), 0) as licencia,
                   coalesce(sum(x.horas) filter (where x.tipo = 'VACACIONES'), 0) as vacaciones
            from public.horas x
            where x.fecha between desde and hasta
            group by x.user_id
        ), a as (
            select y.user_id,
                   coalesce(sum(y.delta) filter (where y.columna = 'feriado'), 0) as feriado,
                   coalesce(sum(y.delta) filter (where y.columna = 'facturable'), 0) as facturable,
                   coalesce(sum(y.delta) filter (where y.columna = 'no_facturable'), 0) as no_facturable,
                   coalesce(sum(y.delta) filter (where y.columna = 'licencia'), 0) as licencia,
                   coalesce(sum(y.delta) filter (where y.columna = 'vacaciones'), 0) as vacaciones
            from public.horas_ajustes y
            where y.fecha between desde and hasta
            group by y.user_id
        ), t as (
            select p.id, p.full_name,
                   coalesce(h.feriado, 0) + coalesce(a.feriado, 0) as feriado,
                   coalesce(h.facturable, 0) + coalesce(a.facturable, 0) as facturable,
                   coalesce(h.no_facturable, 0) + coalesce(a.no_facturable, 0) as no_facturable,
                   coalesce(h.licencia, 0) + coalesce(a.licencia, 0) as licencia,
                   coalesce(h.vacaciones, 0) + coalesce(a.vacaciones, 0) as vacaciones
            from public.profiles p
            left join h on h.user_id = p.id
            left join a on a.user_id = p.id
            where p.en_informe
              and (p.active or h.user_id is not null or a.user_id is not null)
        )
        select t.id, t.full_name, t.feriado, t.facturable, t.no_facturable, t.licencia, t.vacaciones,
               t.feriado + t.facturable + t.no_facturable + t.licencia + t.vacaciones
        from t
        order by t.full_name;
end;
$$;

revoke all on function public.horas_resumen(date, date) from public, anon;
grant execute on function public.horas_resumen(date, date) to authenticated;
