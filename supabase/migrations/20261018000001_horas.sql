-- QA BCR Suite v3 — Registro de horas semanales
-- Reemplaza el libro de Excel "Horas semanales" (una pestaña por QA) y el
-- informe "Horas mensuales equipo QA".
--   · Cada QA carga sus líneas: día, Soli/PBI, tarea, tipo, horas y cuántas
--     de esas horas se pueden facturar (puede ser menos que las trabajadas).
--   · Feriado, licencia/incapacidad/citas y vacaciones/permisos son una línea
--     más del día, con sus horas y sin horas facturables.
--   · Un QA ve y cambia solo sus líneas. QA_LEAD y ADMIN ven y corrigen las
--     de todos.
--   · El consolidado (totales por persona) lo ven todos los usuarios activos,
--     con horas_resumen(); el detalle de tareas de otros no.
-- Requiere las funciones private.* de 20261015000002_rls.sql.

create table public.horas (
    id bigint generated by default as identity primary key,
    user_id uuid not null default auth.uid() references public.profiles(id) on delete cascade,
    -- Solo de lunes a viernes, como el Excel.
    fecha date not null check (extract(isodow from fecha) between 1 and 5),
    tipo text not null default 'TRABAJO'
        check (tipo in ('TRABAJO', 'FERIADO', 'LICENCIA', 'VACACIONES')),
    soli text not null default '' check (char_length(soli) <= 60),
    tarea text not null default '' check (char_length(tarea) <= 300),
    horas numeric(4, 2) not null check (horas > 0 and horas <= 24),
    facturable numeric(4, 2) not null default 0 check (facturable >= 0 and facturable <= horas),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    updated_by uuid references public.profiles(id) on delete set null,
    constraint horas_facturable_solo_trabajo check (tipo = 'TRABAJO' or facturable = 0)
);

create index horas_user_fecha on public.horas (user_id, fecha);
create index horas_fecha on public.horas (fecha);

-- updated_at y updated_by los pone la base: el cliente no puede falsearlos.
create or replace function public.horas_touch()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.updated_at = now();
    new.updated_by = auth.uid();
    if tg_op = 'INSERT' then
        new.created_at = now();
    end if;
    if new.tipo <> 'TRABAJO' then
        new.facturable = 0;
    end if;
    return new;
end;
$$;

create trigger horas_touch
before insert or update on public.horas
for each row execute function public.horas_touch();

alter table public.horas enable row level security;

create policy horas_select
on public.horas for select to authenticated
using (
    (user_id = (select auth.uid()) and (select private.is_active_user()))
    or (select private.is_lead())
);

create policy horas_insert
on public.horas for insert to authenticated
with check (
    (user_id = (select auth.uid()) and (select private.is_active_user()))
    or (select private.is_lead())
);

create policy horas_update
on public.horas for update to authenticated
using (
    (user_id = (select auth.uid()) and (select private.is_active_user()))
    or (select private.is_lead())
)
with check (
    (user_id = (select auth.uid()) and (select private.is_active_user()))
    or (select private.is_lead())
);

create policy horas_delete
on public.horas for delete to authenticated
using (
    (user_id = (select auth.uid()) and (select private.is_active_user()))
    or (select private.is_lead())
);

-- user_id no se puede cambiar después de creada la línea.
grant select, delete on public.horas to authenticated;
grant insert (user_id, fecha, tipo, soli, tarea, horas, facturable) on public.horas to authenticated;
grant update (fecha, tipo, soli, tarea, horas, facturable) on public.horas to authenticated;
grant usage, select on sequence public.horas_id_seq to authenticated;
revoke all on public.horas from anon;
grant all on public.horas to service_role;

-- Consolidado por persona entre dos fechas (máximo 62 días). Lo puede pedir
-- cualquier usuario activo: devuelve solo totales, nunca las tareas.
-- Salen todos los perfiles activos (aunque no hayan cargado nada) y los
-- inactivos que tengan horas en el período.
create or replace function public.horas_resumen(desde date, hasta date)
returns table (
    user_id uuid,
    full_name text,
    feriado numeric,
    facturable numeric,
    no_facturable numeric,
    licencia numeric,
    vacaciones numeric,
    total numeric
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
    if not private.is_active_user() then
        raise exception 'Usuario sin acceso' using errcode = '42501';
    end if;
    if desde is null or hasta is null or hasta < desde or hasta - desde > 62 then
        raise exception 'Período inválido' using errcode = '22023';
    end if;
    return query
        select p.id,
               p.full_name,
               coalesce(sum(h.horas) filter (where h.tipo = 'FERIADO'), 0),
               coalesce(sum(h.facturable) filter (where h.tipo = 'TRABAJO'), 0),
               coalesce(sum(h.horas - h.facturable) filter (where h.tipo = 'TRABAJO'), 0),
               coalesce(sum(h.horas) filter (where h.tipo = 'LICENCIA'), 0),
               coalesce(sum(h.horas) filter (where h.tipo = 'VACACIONES'), 0),
               coalesce(sum(h.horas), 0)
        from public.profiles p
        left join public.horas h
            on h.user_id = p.id and h.fecha between desde and hasta
        group by p.id, p.full_name, p.active
        having p.active or count(h.id) > 0
        order by p.full_name;
end;
$$;

revoke all on function public.horas_resumen(date, date) from public, anon;
grant execute on function public.horas_resumen(date, date) to authenticated;
