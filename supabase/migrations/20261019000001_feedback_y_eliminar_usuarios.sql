-- QA BCR Suite v3 — Feedback y eliminar usuarios
--   · Cualquier usuario activo deja feedback (ideas, errores, pedidos). Solo un
--     ADMIN lo lee, lo marca como leído o lo borra. Quien lo envía no lo vuelve
--     a ver. Queda guardado el nombre de quien lo envió, aunque después se
--     elimine su usuario.
--   · Un ADMIN puede eliminar usuarios (lo hace la Edge Function admin-create-user
--     con action 'delete_user'). Al eliminar el usuario se borran su perfil, sus
--     horas y los ajustes de sus horas; en solicitudes, horas y feedback
--     de otros queda el registro sin el "modificado por".
-- Requiere 20261018000003_horas_ajustes.sql.

-- El historial del QA Generator no impedía borrar el usuario por la FK sin
-- "on delete": ahora se borra con él (igual que sus horas).
alter table public.qa_generations drop constraint if exists qa_generations_user_id_fkey;
alter table public.qa_generations
    add constraint qa_generations_user_id_fkey
    foreign key (user_id) references auth.users(id) on delete cascade;

create table public.feedback (
    id bigint generated by default as identity primary key,
    user_id uuid default auth.uid() references public.profiles(id) on delete set null,
    autor text not null default '',
    mensaje text not null check (char_length(btrim(mensaje)) between 1 and 2000),
    leido boolean not null default false,
    created_at timestamptz not null default now()
);

create index feedback_created on public.feedback (created_at desc);

-- Quién lo envía lo pone la base (no se puede enviar a nombre de otro), con un
-- límite de 20 por persona por día para que no se llene de mensajes.
create or replace function public.feedback_before_insert()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    new.user_id = auth.uid();
    new.autor = coalesce((select p.full_name from public.profiles p where p.id = auth.uid()), '');
    new.mensaje = btrim(new.mensaje);
    new.leido = false;
    new.created_at = now();
    if (select count(*) from public.feedback f
        where f.user_id = auth.uid() and f.created_at > now() - interval '1 day') >= 20 then
        raise exception 'Llegaste al máximo de 20 mensajes por día' using errcode = '54000';
    end if;
    return new;
end;
$$;

create trigger feedback_before_insert
before insert on public.feedback
for each row execute function public.feedback_before_insert();

alter table public.feedback enable row level security;

create policy feedback_insert
on public.feedback for insert to authenticated
with check ((select private.is_active_user()));

create policy feedback_admin_select
on public.feedback for select to authenticated
using ((select private.is_admin()));

create policy feedback_admin_update
on public.feedback for update to authenticated
using ((select private.is_admin()))
with check ((select private.is_admin()));

create policy feedback_admin_delete
on public.feedback for delete to authenticated
using ((select private.is_admin()));

grant select, delete on public.feedback to authenticated;
grant insert (mensaje) on public.feedback to authenticated;
grant update (leido) on public.feedback to authenticated;
grant usage, select on sequence public.feedback_id_seq to authenticated;
revoke all on public.feedback from anon;
grant all on public.feedback to service_role;
revoke all on function public.feedback_before_insert() from public, anon, authenticated;
