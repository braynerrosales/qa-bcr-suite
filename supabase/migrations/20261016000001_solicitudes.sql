-- QA BCR Suite v3 — Control de solicitudes (para QA Lead y Admin)
-- Una sola lista compartida. Solo ADMIN y QA_LEAD activos la ven y la editan;
-- un QA no puede ni leerla (RLS), aunque llame a la API directamente.
-- Requiere las funciones private.is_lead() de 20261015000002_rls.sql.

create table public.solicitudes (
    id bigint generated by default as identity primary key,
    nombre text not null check (char_length(trim(nombre)) between 1 and 300),
    informe_semanal boolean not null default false,
    -- Nombres elegidos de las personas del Daily. Se guarda el texto (no el id)
    -- para que el historial no cambie si alguien sale del Daily.
    encargados text[] not null default '{}'
        check (cardinality(encargados) <= 10 and array_position(encargados, '') is null),
    horas numeric(6, 1) check (horas >= 0),
    pend_plan boolean not null default false,
    pend_actualizar boolean not null default false,
    plan_enviado boolean not null default false,
    cierre_enviado boolean not null default false,
    cierra date,
    observaciones text not null default '' check (char_length(observaciones) <= 2000),
    cerrada boolean not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    updated_by uuid references public.profiles(id) on delete set null
);

-- updated_at y updated_by los pone la base: el cliente no puede falsearlos.
create or replace function public.solicitudes_touch()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.updated_at = now();
    new.updated_by = auth.uid();
    if tg_op = 'INSERT' then
        new.created_at = now();
    end if;
    return new;
end;
$$;

create trigger solicitudes_touch
before insert or update on public.solicitudes
for each row execute function public.solicitudes_touch();

alter table public.solicitudes enable row level security;

create policy solicitudes_select
on public.solicitudes for select to authenticated
using ((select private.is_lead()));

create policy solicitudes_insert
on public.solicitudes for insert to authenticated
with check ((select private.is_lead()));

create policy solicitudes_update
on public.solicitudes for update to authenticated
using ((select private.is_lead()))
with check ((select private.is_lead()));

create policy solicitudes_delete
on public.solicitudes for delete to authenticated
using ((select private.is_lead()));

-- Permisos explícitos (los proyectos nuevos de Supabase no dan ninguno por defecto).
-- Sin created_at / updated_at / updated_by: los maneja el trigger.
grant select, delete on public.solicitudes to authenticated;
grant insert (nombre, informe_semanal, encargados, horas, pend_plan, pend_actualizar,
              plan_enviado, cierre_enviado, cierra, observaciones, cerrada)
    on public.solicitudes to authenticated;
grant update (nombre, informe_semanal, encargados, horas, pend_plan, pend_actualizar,
              plan_enviado, cierre_enviado, cierra, observaciones, cerrada)
    on public.solicitudes to authenticated;
grant usage, select on sequence public.solicitudes_id_seq to authenticated;
revoke all on public.solicitudes from anon;
grant all on public.solicitudes to service_role;
